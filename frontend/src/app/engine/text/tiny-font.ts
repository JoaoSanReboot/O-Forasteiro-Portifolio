type Mark = 'tilde' | 'acute' | 'circ' | 'ced';
const TMARK: Record<string, readonly [string, Mark]> = {
  'Ã': ['A', 'tilde'], 'Á': ['A', 'acute'], 'É': ['E', 'acute'], 'Ê': ['E', 'circ'], 'Ó': ['O', 'acute'], 'Í': ['I', 'acute'], 'Ç': ['C', 'ced'], 'Ú': ['U', 'acute'],
};
const glyph = (ch: string): readonly string[] => TG[TMARK[ch] ? TMARK[ch][0] : ch] || TG[' '];

export const tinyWidth = (text: string): number => [...text].reduce((w, ch) => w + glyph(ch)[0].length + 1, -1);

export function tinyText(g: Ctx, text: string, x: number, y: number, color: string, center = false): void {
  let cx = Math.round(center ? x - tinyWidth(text) / 2 : x);
  g.fillStyle = color;
  for (const ch of text) {
    const gl = glyph(ch);
    gl.forEach((row, ry) => [...row].forEach((b, rx) => { if (b === '1') g.fillRect(cx + rx, y + ry, 1, 1); }));
    const mk = TMARK[ch] && TMARK[ch][1];
    if (mk === 'tilde') { g.fillRect(cx, y - 2, 2, 1); g.fillRect(cx + 2, y - 3, 1, 1); }
    if (mk === 'acute') g.fillRect(cx + 2, y - 2, 1, 1);
    if (mk === 'circ') { g.fillRect(cx + 1, y - 2, 1, 1); }
    if (mk === 'ced') g.fillRect(cx + 1, y + 5, 1, 1);
    cx += gl[0].length + 1;
  }
}
